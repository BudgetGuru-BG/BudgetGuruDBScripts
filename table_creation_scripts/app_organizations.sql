DROP TABLE IF EXISTS PUBLIC.APP_ORGANIZATIONS;
DROP TABLE IF EXISTS PUBLIC.APP_ORGANIZATIONS_AUDIT_LOG;
DROP SEQUENCE IF EXISTS PUBLIC.APP_ORGANIZATIONS_ID_SEQ;
DROP SEQUENCE IF EXISTS PUBLIC.APP_ORGANIZATIONS_AUDIT_LOG_ID_SEQ;

CREATE SEQUENCE PUBLIC.APP_ORGANIZATIONS_ID_SEQ
    INCREMENT by 1
    MINVALUE 1
    MAXVALUE 9223372036854775807
    START 1
    CACHE 1
    NO CYCLE;

CREATE TABLE
    PUBLIC.APP_ORGANIZATIONS (
        ORGANIZATION_ID INT8 NOT NULL GENERATED BY DEFAULT AS IDENTITY (
            INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 START 1 CACHE 1 NO CYCLE
        ),
        TENANT_ID INT8 NOT NULL,
        ORGANIZATION_NAME TEXT NOT NULL,
        ORGANIZATION_CODE TEXT NOT NULL,
        DESCRIPTION TEXT,
        ADDRESS_LINE_1 TEXT,
        ADDRESS_LINE_2 TEXT,
        ADDRESS_CITY TEXT,
        ADDRESS_REGION TEXT,
        ADDRESS_STATE TEXT,
        ADDRESS_COUNTRY TEXT,
        STATUS TEXT,
        CREATED_ON TIMESTAMP NOT NULL,
        CREATED_BY TEXT NOT NULL,
        UPDATED_ON TIMESTAMP NOT NULL,
        UPDATED_BY TEXT NOT NULL,
        
        CONSTRAINT ORGANIZATION_ID_PKEY PRIMARY KEY (ORGANIZATION_ID),
        CONSTRAINT FK_ORGANIZATION_TENANT FOREIGN KEY (TENANT_ID) REFERENCES PUBLIC.APP_TENANTS (TENANT_ID)
    );


CREATE UNIQUE INDEX ORGANIZATION_NAME_IDX ON PUBLIC.APP_ORGANIZATIONS USING BTREE (ORGANIZATION_NAME);